import 'package:flutter/widgets.dart';

/// Locale controller shared by the whole app (es / en).
class LocaleController extends ValueNotifier<String> {
  LocaleController([super.value = 'es']);
  void toggle() => value = value == 'es' ? 'en' : 'es';
}

class LocaleScope extends InheritedNotifier<LocaleController> {
  const LocaleScope({super.key, required LocaleController controller, required super.child})
      : super(notifier: controller);

  static LocaleController controllerOf(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<LocaleScope>()!.notifier!;

  static String of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<LocaleScope>();
    return scope?.notifier?.value ?? 'es';
  }
}

/// Translate a key for the current locale.
String tr(BuildContext context, String key, [Map<String, String> args = const {}]) {
  final lang = LocaleScope.of(context);
  var s = _strings[lang]?[key] ?? _strings['es']?[key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// Pick the localized value from a backend {'es': ..., 'en': ...} map.
String loc(BuildContext context, dynamic value) {
  if (value is Map) {
    final lang = LocaleScope.of(context);
    return (value[lang] ?? value['es'] ?? '').toString();
  }
  return value?.toString() ?? '';
}


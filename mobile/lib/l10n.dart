/// Format a number for display in the current locale (no excessive decimals).
String fmtNum(BuildContext context, num? v, {int decimals = 1, bool signed = false}) {
  if (v == null) return '—';
  final lang = LocaleScope.of(context);
  var r = double.parse(v.toStringAsFixed(decimals));
  if (r == 0) r = 0; // no "-0"
  var s = r.abs().toStringAsFixed(decimals);
  if (decimals > 0 && s.contains('.')) s = s.replaceFirst(RegExp(r'\.?0+$'), '');
  final parts = s.split('.');
  final grouped = parts[0].replaceAllMapped(RegExp(r'\B(?=(\d{3})+(?!\d))'), (_) => lang == 'es' ? ' ' : ',');
  s = parts.length > 1 ? '$grouped${lang == 'es' ? ',' : '.'}${parts[1]}' : grouped;
  if (r < 0) s = '−$s';
  if (signed && r > 0) s = '+$s';
  return s;
}

String fmtDate(BuildContext context, String? iso) {
  if (iso == null || iso.isEmpty) return '—';
  final d = DateTime.tryParse(iso);
  if (d == null) return iso;
  final lang = LocaleScope.of(context);
  const es = ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'];
  const en = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return lang == 'es' ? '${d.day} ${es[d.month - 1]} ${d.year}' : '${en[d.month - 1]} ${d.day}, ${d.year}';
}
